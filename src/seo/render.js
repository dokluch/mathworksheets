const AUTHOR_ID = `${SITE_URL}/#author`

function websiteId(locale) {
  return `${absoluteUrl(homeRoute(locale).path)}#website`
}

function authorNode() {
  return { '@type': 'Person', '@id': AUTHOR_ID, name: AUTHOR.name, url: AUTHOR.url }
}

function websiteNode(locale) {
  const home = absoluteUrl(homeRoute(locale).path)
  return {
    '@type': 'WebSite',
    '@id': websiteId(locale),
    url: locale === DEFAULT_LOCALE ? `${SITE_URL}/` : home,
    name: BRAND,
    alternateName: [t(locale, 'site.brandAlt'), pageTitle(homeRoute(locale))],
    description: t(locale, 'site.description'),
    inLanguage: langOf(locale),
    publisher: { '@id': AUTHOR_ID },
  }
}

export function structuredData(route) {
  const { locale } = route
  const lang = langOf(locale)
  const sheets = localizedWorksheets(locale)

  if (route.kind === 'home') {
    const home = locale === DEFAULT_LOCALE ? `${SITE_URL}/` : absoluteUrl(route.path)
    return {
      '@context': 'https://schema.org',
      '@graph': [
        websiteNode(locale),
        authorNode(),
        {
          '@type': 'WebApplication',
          '@id': `${home}#app`,
          name: BRAND,
          alternateName: t(locale, 'site.brandAlt'),
          url: home,
          description: t(locale, 'site.description'),
          applicationCategory: 'EducationalApplication',
          operatingSystem: 'Any (web browser)',
          browserRequirements: 'Requires JavaScript to generate and print worksheets',
          isAccessibleForFree: true,
          offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
          license: LICENSE_URL,
          author: { '@id': AUTHOR_ID },
          screenshot: absoluteUrl(OG_IMAGE_PATH),
          inLanguage: lang,
          featureList: sheets.map(w => t(locale, 'seo.featureItem', { label: w.label, shortDesc: w.shortDesc })),
          audience: { '@type': 'EducationalAudience', educationalRole: 'student' },
          isPartOf: { '@id': websiteId(locale) },
        },
        {
          '@type': 'ItemList',
          name: t(locale, 'seo.worksheetList', { brand: BRAND }),
          itemListElement: sheets.map((w, i) => ({
            '@type': 'ListItem',
            position: i + 1,
            name: w.label,
            url: absoluteUrl(worksheetRoute(w, locale).path),
          })),
        },
      ],
    }
  }

  if (route.kind === 'page') {
    const page = route.page
    return {
      '@context': 'https://schema.org',
      '@graph': [
        {
          '@type': 'WebPage',
          '@id': `${absoluteUrl(route.path)}#page`,
          url: absoluteUrl(route.path),
          name: pageTitle(route),
          description: pageDescription(route),
          isPartOf: { '@id': websiteId(locale) },
          inLanguage: lang,
          dateModified: page.updated,
          license: LICENSE_URL,
          author: { '@id': AUTHOR_ID },
        },
        authorNode(),
        breadcrumbs([{ name: BRAND, path: homeRoute(locale).path }, { name: page.navLabel, path: route.path }]),
      ],
    }
  }

  const ws = route.worksheet
  const url = absoluteUrl(route.path)
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'LearningResource',
        '@id': `${url}#resource`,
        url,
        name: t(locale, 'seo.worksheetHeading', { label: ws.label }),
        alternateName: t(locale, 'seo.worksheetName', { brand: BRAND, label: ws.label }),
        description: ws.longDesc,
        learningResourceType: t(locale, ws.interactive ? 'seo.learningResourceInteractive' : 'seo.learningResourceWorksheet'),
        educationalLevel: gradeLevelText(ws, locale),
        typicalAgeRange: agesForGrades(ws.grades),
        teaches: ws.skills,
        educationalAlignment: ws.skills.map(skill => ({ '@type': 'AlignmentObject', alignmentType: 'teaches', targetName: skill })),
        educationalUse: 'practice',
        dateModified: ws.updated,
        audience: { '@type': 'EducationalAudience', educationalRole: 'student' },
        inLanguage: lang,
        isAccessibleForFree: true,
        license: LICENSE_URL,
        author: { '@id': AUTHOR_ID },
        isPartOf: { '@id': websiteId(locale) },
        encoding: [{ '@type': 'MediaObject', encodingFormat: 'text/markdown', contentUrl: absoluteUrl(route.md) }],
        image: absoluteUrl(ogImagePath(route)),
      },
      {
        '@type': 'FAQPage',
        '@id': `${url}#faq`,
        inLanguage: lang,
        isPartOf: { '@id': websiteId(locale) },
        mainEntity: ws.faq.map(item => ({
          '@type': 'Question',
          name: item.q,
          acceptedAnswer: { '@type': 'Answer', text: item.a },
        })),
      },
      authorNode(),
      breadcrumbs([{ name: BRAND, path: homeRoute(locale).path }, { name: ws.label, path: route.path }]),
    ],
  }
}

function breadcrumbs(items) {
  return {
    '@type': 'BreadcrumbList',
    itemListElement: items.map((it, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: it.name,
      item: absoluteUrl(it.path),
    })),
  }
}

/* ────────────────────────────── <head> ────────────────────────────── */

function hreflangLinks(route) {
  const lines = LOCALES.map(l =>
    `<link rel="alternate" hreflang="${LOCALE_META[l].hreflang}" href="${attr(absoluteUrl(sameRouteIn(route, l).path))}" />`)
  lines.push(`<link rel="alternate" hreflang="x-default" href="${attr(absoluteUrl(sameRouteIn(route, DEFAULT_LOCALE).path))}" />`)
  return lines
}

export function renderHead(route) {
  const { locale } = route
  const title = pageTitle(route)
  const description = pageDescription(route)
  const url = absoluteUrl(route.path)
  const image = absoluteUrl(ogImagePath(route))
  const lines = [
    `<title>${escapeHtml(title)}</title>`,
    `<meta name="description" content="${attr(description)}" />`,
    `<meta name="robots" content="index, follow, max-image-preview:large" />`,
    `<meta name="theme-color" content="${THEME_COLOR}" />`,
    `<meta name="application-name" content="${BRAND}" />`,
    `<meta name="author" content="${attr(AUTHOR.name)}" />`,
    `<link rel="canonical" href="${attr(url)}" />`,
    ...hreflangLinks(route),
    `<link rel="alternate" type="text/markdown" href="${attr(absoluteUrl(route.md))}" title="${attr(title)} (Markdown)" />`,
    `<link rel="sitemap" type="application/xml" href="${attr(absoluteUrl('/sitemap.xml'))}" />`,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${BRAND}" />`,
    `<meta property="og:locale" content="${LOCALE_META[locale].og}" />`,
    ...LOCALES.filter(l => l !== locale).map(l => `<meta property="og:locale:alternate" content="${LOCALE_META[l].og}" />`),
    `<meta property="og:url" content="${attr(url)}" />`,
    `<meta property="og:title" content="${attr(title)}" />`,
    `<meta property="og:description" content="${attr(description)}" />`,
    `<meta property="og:image" content="${attr(image)}" />`,
    `<meta property="og:image:type" content="image/png" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="${attr(ogImageAlt(route))}" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${attr(title)}" />`,
    `<meta name="twitter:description" content="${attr(description)}" />`,
    `<meta name="twitter:image" content="${attr(image)}" />`,
    `<meta name="twitter:image:alt" content="${attr(ogImageAlt(route))}" />`,
    jsonLd(structuredData(route)),
  ]
  return lines.join('\n    ')
}

