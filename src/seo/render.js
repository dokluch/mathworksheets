function breadcrumbNav(locale, current) {
  return `<nav aria-label="Breadcrumb"><a href="${homeRoute(locale).path}">${BRAND}</a> › ${escapeHtml(current)}</nav>`
}

/** Links shown in the site footer (React and static HTML share this list). */
export function siteFooterLinks(locale = DEFAULT_LOCALE) {
  return [
    ...localizedPages(locale).map(p => ({ label: p.navLabel, path: pageRoute(p, locale).path, external: false })),
    { label: 'GitHub', path: GITHUB_URL, external: true },
  ]
}

export function footerHtml({ year = new Date().getFullYear(), locale = DEFAULT_LOCALE } = {}) {
  const links = siteFooterLinks(locale)
    .map(l => `<a href="${l.path}"${l.external ? ' rel="noopener noreferrer"' : ''}>${escapeHtml(l.label)}</a>`)
    .join('\n        ')
  return `<footer class="site-footer no-print">
      <nav class="site-footer-links" aria-label="${attr(t(locale, 'static.footerSite'))}">
        ${links}
      </nav>
      <p class="site-footer-legal">© ${year} ${escapeHtml(OPERATOR)} · <a href="${LICENSE_URL}" rel="license noopener">${LICENSE_NAME}</a></p>
    </footer>`
}

