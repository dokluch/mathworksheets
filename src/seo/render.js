/* ────────────────────────────── routes ────────────────────────────── */

export function homeRoute(locale = DEFAULT_LOCALE) {
  if (locale === DEFAULT_LOCALE) {
    return { kind: 'home', locale, path: '/', md: '/index.md', html: 'index.html', mdFile: 'index.md' }
  }
  return { kind: 'home', locale, path: `/${locale}`, md: `/${locale}.md`, html: `${locale}.html`, mdFile: `${locale}.md` }
}

function localizedFiles(locale, rel) {
  const prefix = localePrefix(locale)
  const file = prefix ? `${locale}/${rel}` : rel
  return { path: `${prefix}/${rel}`, md: `${prefix}/${rel}.md`, html: `${file}.html`, mdFile: `${file}.md` }
}

export function worksheetRoute(ws, locale = DEFAULT_LOCALE) {
  const source = findWorksheetById(ws.id) ?? ws
  return {
    kind: 'worksheet',
    locale,
    worksheet: localizeWorksheet(source, locale),
    ...localizedFiles(locale, `worksheets/${source.slug}`),
  }
}

/** About / Privacy / Terms (src/pages.js), translated per locale. */
export function pageRoute(page, locale = DEFAULT_LOCALE) {
  const source = findPageById(page.id) ?? page
  return { kind: 'page', locale, page: localizePage(source, locale), ...localizedFiles(locale, source.slug) }
}

export function pageRoutes(locale = DEFAULT_LOCALE) {
  return PAGES.map(p => pageRoute(p, locale))
}

/** Open Graph preview image for a route; generated by `npm run og` (scripts/og-images.mjs). Shared by every locale; static pages reuse the home card. */
export function ogImagePath(route) {
  if (route.kind === 'worksheet') return `/og/${route.worksheet.slug}.png`
  return OG_IMAGE_PATH
}

export function ogImageAlt(route) {
  const { locale } = route
  if (route.kind === 'worksheet') return t(locale, 'seo.ogAltWorksheet', { label: route.worksheet.label, brand: BRAND })
  return t(locale, 'seo.ogAltHome', { brand: BRAND, tagline: t(locale, 'site.tagline') })
}

/** All routes (every locale, English first), or the routes of one locale. */
export function routes(locale) {
  const locales = locale ? [locale] : LOCALES
  return locales.flatMap(l => [homeRoute(l), ...WORKSHEETS.map(w => worksheetRoute(w, l)), ...pageRoutes(l)])
}

/** The same page in another locale. */
export function sameRouteIn(route, locale) {
  if (route.kind === 'home') return homeRoute(locale)
  if (route.kind === 'page') return pageRoute(route.page, locale)
  return worksheetRoute(route.worksheet, locale)
}

/** Normalise a pathname (strip trailing slash, collapse `/index` and `/index.html`). */
export function normalizePath(pathname) {
  let p = pathname || '/'
  try { p = decodeURIComponent(p) } catch { /* keep raw */ }
  if (p.length > 1) p = p.replace(/\/+$/, '')
  p = p.replace(/\/index(?:\.html)?$/, '')
  if (p === '') p = '/'
  return p
}

export function findRoute(pathname) {
  const { locale, rest } = splitLocale(normalizePath(pathname))
  if (rest === '/') return homeRoute(locale)
  const page = /^\/[a-z0-9-]+$/.test(rest) ? findPageBySlug(rest.slice(1)) : null
  if (page) return pageRoute(page, locale)
  const m = rest.match(/^\/worksheets\/([a-z0-9-]+)$/)
  if (m) {
    const ws = findWorksheetBySlug(m[1])
    return ws ? worksheetRoute(ws, locale) : null
  }
  return null
}

/* ────────────────────────────── helpers ────────────────────────────── */

export function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function attr(s) {
  return escapeHtml(s)
}

/** Mark a param as trusted HTML for `html()` (links, <code>, …). */
function raw(fragment) {
  return { __html: fragment }
}

/** Translate for HTML: escape the message template, then interpolate params (escaped unless wrapped with raw()). */
function html(locale, key, params = {}) {
  const safe = {}
  for (const [k, v] of Object.entries(params)) {
    safe[k] = v && typeof v === 'object' && '__html' in v ? v.__html : escapeHtml(String(v))
  }
  return interpolate(escapeHtml(t(locale, key)), safe)
}

/** Translate for Markdown / plain text. */
function text(locale, key, params = {}) {
  return interpolate(t(locale, key), params)
}

function code(s) {
  return raw(`<code>${escapeHtml(s)}</code>`)
}

function link(href, label) {
  return raw(`<a href="${attr(href)}">${escapeHtml(label)}</a>`)
}

const LINK_RE = /\[([^\]]+)\]\(([^)\s]+)\)/g

/** Plain text with optional `[label](url)` links → escaped HTML with anchors; site-relative links get the locale prefix. */
export function inlineHtml(text, locale = DEFAULT_LOCALE) {
  return escapeHtml(text).replace(LINK_RE, (_, label, href) => {
    const external = /^https?:\/\//.test(href)
    const target = href.startsWith('/') ? localizePath(href, locale) : href
    return `<a href="${target}"${external ? ' rel="noopener"' : ''}>${label}</a>`
  })
}

/** Same text for Markdown: site-relative links become absolute, locale-prefixed URLs. */
export function inlineMarkdown(text, locale = DEFAULT_LOCALE) {
  return text.replace(LINK_RE, (_, label, href) => `[${label}](${href.startsWith('/') ? absoluteUrl(localizePath(href, locale)) : href})`)
}

function jsonLd(obj) {
  // "</" must not appear inside a <script> element.
  return `<script type="application/ld+json">${JSON.stringify(obj).replace(/<\//g, '<\\/')}</script>`
}


