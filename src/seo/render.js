function sectionMarkdown(section, locale) {
  const parts = [`## ${section.heading}`, '']
  for (const p of section.paragraphs || []) parts.push(inlineMarkdown(p, locale), '')
  if (section.items?.length) parts.push(...section.items.map(i => `- ${inlineMarkdown(i, locale)}`), '')
  return parts.join('\n').trimEnd()
}

export function renderPageMarkdown(route) {
  const { locale, page } = route
  const m = (key, params) => text(locale, key, params)
  const more = [
    { label: m('md.homeLink', { brand: BRAND }), md: homeRoute(locale).md },
    ...localizedPages(locale).filter(p => p.id !== page.id).map(p => ({ label: p.title, md: pageRoute(p, locale).md })),
  ].map(l => `- ${mdLink(l.label, l.md)}`).join('\n')
  return `# ${page.title}

> ${inlineMarkdown(page.description, locale)}

**${m('md.lastUpdated')}:** ${formatDate(page.updated, locale)}
**${m('static.worksheet.url')}:** ${absoluteUrl(route.path)}

${page.sections.map(s => sectionMarkdown(s, locale)).join('\n\n')}

## ${m('md.moreFrom', { brand: BRAND })}

${more}
`
}

export function renderMarkdown(route) {
  if (route.kind === 'home') return renderIndexMarkdown(route)
  if (route.kind === 'developers') return renderDevelopersMarkdown(route)
  if (route.kind === 'page') return renderPageMarkdown(route)
  return renderWorksheetMarkdown(route)
}

