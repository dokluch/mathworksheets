function formatDate(iso, locale = DEFAULT_LOCALE) {
  const d = new Date(`${iso}T00:00:00Z`)
  return d.toLocaleDateString(langOf(locale), { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' })
}

function sectionHtml(section, locale) {
  const parts = [`<h2>${escapeHtml(section.heading)}</h2>`]
  for (const p of section.paragraphs || []) parts.push(`<p>${inlineHtml(p, locale)}</p>`)
  if (section.items?.length) {
    parts.push(`<ul>\n        ${section.items.map(i => `<li>${inlineHtml(i, locale)}</li>`).join('\n        ')}\n      </ul>`)
  }
  return parts.join('\n      ')
}

function pageBody(route) {
  const { locale, page } = route
  return `${breadcrumbNav(locale, page.navLabel)}
      <header class="catalog-header">
        <div class="catalog-brand">
          <h1 class="catalog-title">${escapeHtml(page.title)}</h1>
          <p class="catalog-subtitle">${html(locale, 'static.lastUpdated', { date: formatDate(page.updated, locale) })}</p>
        </div>
      </header>
      <section class="static-intro">
        <p>${inlineHtml(page.description, locale)}</p>
      </section>
      ${page.sections.map(s => sectionHtml(s, locale)).join('\n      ')}`
}

/**
 * Inner HTML of a non-worksheet page (developers, about, privacy, terms):
 * used inside <main class="catalog catalog--full static-page"> both by the
 * prerendered fallback and by the React StaticPage component.
 */
export function staticBody(route) {
  if (route.kind === 'developers') return developersBody(route)
  if (route.kind === 'page') return pageBody(route)
  throw new Error(`staticBody: no static body for route kind "${route.kind}"`)
}

function staticMain(route) {
  return `<main class="catalog catalog--full static-page">
      ${staticBody(route)}
    </main>`
}

export function renderStaticContent(route) {
  const inner =
    route.kind === 'home' ? homeContent(route) :
    route.kind === 'worksheet' ? worksheetContent(route) :
    staticMain(route)
  return `<div id="static-content">\n    ${inner}\n    ${footerHtml({ locale: route.locale })}\n    </div>`
}

/** Replace the marker blocks in an HTML template with this route's head and content, and set <html lang>. */
export function injectRoute(template, route) {
  const headRe = new RegExp(`${HEAD_START}[\\s\\S]*?${HEAD_END.replace('/', '\\/')}`)
  const contentRe = new RegExp(`${CONTENT_START}[\\s\\S]*?${CONTENT_END.replace('/', '\\/')}`)
  if (!headRe.test(template)) throw new Error('index.html is missing the <!-- seo:head --> … <!-- /seo:head --> markers')
  if (!contentRe.test(template)) throw new Error('index.html is missing the <!-- seo:content --> … <!-- /seo:content --> markers')
  return template
    .replace(/<html\b([^>]*)>/, (m, attrs) => `<html${attrs.replace(/\s+lang="[^"]*"/, '')} lang="${langOf(route.locale)}">`)
    .replace(headRe, () => `${HEAD_START}\n    ${renderHead(route)}\n    ${HEAD_END}`)
    .replace(contentRe, () => `${CONTENT_START}\n    ${renderStaticContent(route)}\n    ${CONTENT_END}`)
}

